/* global console */
// Builds supabase/functions/_dashboard/notify-event-status.ts: a single file to
// paste into the Supabase dashboard (Edge Functions → Deploy a new function → Via
// Editor). It uses the same email template as the project's Edge Function
// (supabase/functions/notify-event-status/template.ts), so the two never drift.
//
//   node scripts/build-dashboard-function.mjs

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const templatePath = path.join(root, 'supabase/functions/notify-event-status/template.ts');
const outPath = path.join(root, 'supabase/functions/_dashboard/notify-event-status.ts');

// The template, without its header comment and without `export` (one file).
const template = fs
  .readFileSync(templatePath, 'utf8')
  .replace(/^(\/\/.*\n)+\n/, '')
  .replace(/^export /gm, '');

const header = `// notify-event-status: single-file version to paste into the Supabase dashboard
// (Edge Functions → Deploy a new function → Via Editor, name: notify-event-status).
//
// GENERATED by scripts/build-dashboard-function.mjs from
// supabase/functions/notify-event-status/template.ts. Edit the template, then
// run: node scripts/build-dashboard-function.mjs
//
// Emails the event's contact (البريد الإلكتروني from Event Registration) when the
// event is approved or declined: ONE99 logo, a fixed message (approved) or the
// saved decline message (declined), and all the event details in a table.
// Sent over SMTP from the team's email account (e.g. Gmail). The logo is loaded
// from SITE_URL/logo-192.png when sending and embedded in the email.
//
// Secrets (dashboard: Edge Functions → Secrets):
//   SMTP_USER   e.g. one.99.stmark@gmail.com
//   SMTP_PASS   Gmail App Password (Google Account → Security → App passwords)
//   SITE_URL    the website, e.g. https://st-mark-sports-team-web-app.vercel.app
//   optional: SMTP_HOST (default smtp.gmail.com), SMTP_PORT (default 465 — Supabase
//   blocks 25 and 587), EMAIL_FROM, EMAIL_REPLY_TO

import { createClient } from 'npm:@supabase/supabase-js@2';
import nodemailer from 'npm:nodemailer@6.10.1';

// ---------------------------------------------------------------- template ---

`;

const server = `
// ------------------------------------------------------------------ server ---

const cors = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'POST, OPTIONS',
};
const json = (status: number, body: Record<string, unknown>) =>
  new Response(JSON.stringify(body), { status, headers: { ...cors, 'Content-Type': 'application/json' } });

/** The logo as base64 from the website, or null if it can't be loaded (email is sent without it). */
async function loadLogo(site: string): Promise<string | null> {
  if (!site) return null;
  try {
    const res = await fetch(\`\${site.replace(/\\/+$/, '')}/logo-192.png\`);
    if (!res.ok) return null;
    const bytes = new Uint8Array(await res.arrayBuffer());
    let binary = '';
    for (let i = 0; i < bytes.length; i += 0x8000) binary += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
    return btoa(binary);
  } catch {
    return null;
  }
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: cors });
  if (req.method !== 'POST') return json(405, { error: 'Method not allowed' });

  // Only logged-in team members (not the public anon key) may send emails.
  const authHeader = req.headers.get('Authorization') ?? '';
  const token = authHeader.replace(/^Bearer\\s+/i, '');
  const supabase = createClient(Deno.env.get('SUPABASE_URL')!, Deno.env.get('SUPABASE_ANON_KEY')!, {
    global: { headers: { Authorization: authHeader } },
  });
  const { data: userData } = await supabase.auth.getUser(token);
  if (!userData?.user) return json(401, { error: 'Login required' });

  const body = (await req.json().catch(() => ({}))) as { event_id?: string };
  if (!body.event_id) return json(400, { error: 'event_id is required' });

  const { data: event, error } = await supabase
    .from('events')
    .select(
      'title, status, decline_reason, event_date, day_name, location, goal, participants_count, responsible_person, phone, email, remarks, schedule',
    )
    .eq('id', body.event_id)
    .maybeSingle();
  if (error) return json(500, { error: error.message });
  if (!event) return json(404, { error: 'Event not found' });
  if (event.status !== 'approved' && event.status !== 'declined') {
    return json(400, { error: \`No email is sent for status "\${event.status}"\` });
  }
  if (!event.email) return json(422, { error: 'This event has no email address' });

  const user = Deno.env.get('SMTP_USER');
  const pass = Deno.env.get('SMTP_PASS');
  if (!user || !pass) return json(500, { error: 'Email is not set up yet (SMTP_USER / SMTP_PASS missing)' });

  const site = Deno.env.get('SITE_URL') ?? '';
  const logo = await loadLogo(site);
  const email = buildStatusEmail(event, site, logo !== null);
  const port = Number(Deno.env.get('SMTP_PORT') || '465');
  const replyTo = Deno.env.get('EMAIL_REPLY_TO');

  try {
    const transporter = nodemailer.createTransport({
      host: Deno.env.get('SMTP_HOST') || 'smtp.gmail.com',
      port,
      secure: port === 465,
      auth: { user, pass },
    });
    await transporter.sendMail({
      from: Deno.env.get('EMAIL_FROM') || \`ONE99 Sports Team <\${user}>\`,
      to: event.email,
      subject: email.subject,
      html: email.html,
      text: email.text,
      ...(replyTo ? { replyTo } : {}),
      attachments: logo ? [{ filename: 'one99-logo.png', content: logo, encoding: 'base64', cid: LOGO_CID }] : [],
    });
  } catch (e) {
    return json(502, { error: \`Could not send email: \${e instanceof Error ? e.message : String(e)}\` });
  }

  return json(200, { sent: true, to: event.email });
});
`;

fs.writeFileSync(outPath, header + template.trimEnd() + '\n' + server);
console.log(`Wrote ${path.relative(root, outPath)}`);
